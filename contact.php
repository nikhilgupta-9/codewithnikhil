  <script>
    document.getElementById("contactForm").addEventListener("submit", async function(e) {
      e.preventDefault();

      const submitBtn = document.getElementById("submitBtn");
      submitBtn.disabled = true;
      submitBtn.innerText = "Sending...";

      const responseBox = document.getElementById("responseMessage");

      const formData = new FormData(this);

      try {
        const response = await fetch("<?= $site ?>util/send_mail.php", {
          method: "POST",
          body: formData,
        });

        const result = await response.json();

        responseBox.classList.remove("d-none");
        responseBox.classList.remove("alert-success", "alert-danger");

        if (result.success) {
          responseBox.classList.add("alert-success");
          responseBox.innerText = result.message;
          document.getElementById("contactForm").reset();

           setTimeout(function(){
            responseBox.classList.add("d-none");
          }, 3000)
        } else {
          responseBox.classList.add("alert-danger");
          responseBox.innerText = result.message;
          
          setTimeout(function(){
            responseBox.classList.add("d-none");
          }, 3000)
        }
      } catch (error) {
        responseBox.classList.remove("d-none");
        responseBox.classList.remove("alert-success", "alert-danger");
        responseBox.classList.add("alert-danger");
        responseBox.innerText = "Something went wrong! Try again later.";
      }

      submitBtn.disabled = false;
      submitBtn.innerText = "Get In Touch";

    })
  </script>

